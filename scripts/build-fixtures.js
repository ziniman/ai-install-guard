#!/usr/bin/env node

'use strict';

// Packs fixtures/<name>/ into hooks/test-support/fixtures.gen.ts. Tests run
// with no file system, so they serve fixture files from this module. Every
// file is base64 so bytes (trailing image data, invisible Unicode) survive
// exactly; a symbolic link is kept as its target, never followed.

const fs = require('fs');
const path = require('path');

const REPO_ROOT = path.resolve(__dirname, '..');
const FIXTURES = path.join(REPO_ROOT, 'fixtures');
const OUT = path.join(REPO_ROOT, 'hooks', 'test-support', 'fixtures.gen.ts');

function walk(dir, rel, files) {
  const names = fs.readdirSync(dir).sort();
  for (const name of names) {
    const full = path.join(dir, name);
    const childRel = rel === '' ? name : `${rel}/${name}`;
    const stat = fs.lstatSync(full);
    if (stat.isSymbolicLink()) {
      files[childRel] = { link: fs.readlinkSync(full) };
    } else if (stat.isDirectory()) {
      walk(full, childRel, files);
    } else if (stat.isFile()) {
      files[childRel] = { base64: fs.readFileSync(full).toString('base64') };
    }
  }
  return files;
}

const fixtures = {};
for (const name of fs.readdirSync(FIXTURES).sort()) {
  const dir = path.join(FIXTURES, name);
  if (fs.lstatSync(dir).isDirectory()) {
    fixtures[name] = walk(dir, '', {});
  }
}

const body = [
  '// Generated by scripts/build-fixtures.js from fixtures/. Do not edit by hand:',
  '// run `npm run build:fixtures` and commit the result.',
  '',
  "import type { FixtureFiles } from './memfs'",
  '',
  `export const FIXTURES: Record<string, FixtureFiles> = ${JSON.stringify(fixtures, null, 2)}`,
  '',
].join('\n');

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, body);
console.log(`  wrote ${path.relative(REPO_ROOT, OUT)} (${Object.keys(fixtures).length} fixtures)`);
